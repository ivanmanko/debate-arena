_ANALYST_META = {
    "Эмпирик": ("🔎", "факты, источники, бремя доказывания"),
    "Логик": ("🧩", "структура аргумента, посылки, софизмы"),
    "Стилмен": ("⚖️", "сильнейшая версия, альтернативы, Оккам"),
}


def lens_names() -> list[str]:
    return list(_LENSES)


def analyst_meta(name: str) -> tuple[str, str]:
    return _ANALYST_META[name]


def analyst_system_prompt(name: str, language: str) -> str:
    return f"{MANIFEST}\n\n{_ANALYST_CORE.format(language=language)}\n\n{_LENSES[name]}"


def _source_block(text: str, question: str | None) -> str:
    block = f"Текст для разбора:\n«««\n{text.strip()}\n»»»"
    if question and question.strip():
        block += f"\n\nЧто именно просят проверить: {question.strip()}"
    return block


def round_one_user(text: str, question: str | None, language: str) -> str:
    return (
        "РАУНД 1 — Независимый разбор. Коллеги работают параллельно, их реплик ты не видишь: "
        "так сделано нарочно, чтобы исключить якорение на чужом ответе.\n\n"
        f"{_source_block(text, question)}\n\n"
        "Разбери текст по протоколу, через свою линзу:\n"
        "1. Ядро: что именно утверждается — нейтрально, без эмоций автора, 1–3 тезиса.\n"
        "2. Факты, интерпретации, эмоции: что проверяемо, что мнение, что проекция.\n"
        "3. Аудит: бремя доказывания, бритва Оккама, уловки — по имени и с цитатой.\n"
        "4. Сильнейшая версия позиции автора — и выдерживает ли она проверку.\n"
        "5. Вывод: что в тексте рационально, что нет, что непроверяемо; какое наблюдение "
        "опровергло бы твой вывод.\n\n"
        f"Объём 250–450 слов. Пиши на языке «{language}»."
    )


def cross_round_user(
    text: str, question: str | None, transcript: str, round_no: int, language: str
) -> str:
    return (
        f"РАУНД {round_no} — Перекрёстная проверка. Теперь ты видишь весь транскрипт.\n\n"
        f"{_source_block(text, question)}\n\n"
        f"Транскрипт обсуждения:\n{transcript}\n\n"
        "Твоя реплика — ровно три блока; каждый начинается с маркера на отдельной строке:\n"
        "Принимаю: — рациональные доводы коллег, которые ты принимаешь: кто, что именно и "
        "почему это сильнее твоей прежней позиции. Если принимать нечего — скажи честно, но "
        "сначала проверь себя дважды.\n"
        "Оспариваю: — конкретные ошибки коллег: цитата или точный пересказ и в чём ошибка "
        "(какой пункт Манифеста нарушен или какой факт упущен). Без придирок к мелочам.\n"
        "Уточняю: — твоя скорректированная позиция по тексту после обсуждения, 3–6 "
        "предложений, и что её опровергло бы.\n\n"
        f"Не повторяй уже сказанное. Объём 200–400 слов. Пиши на языке «{language}»."
    )


_JUDGE_CORE = """Ты — беспристрастный судья рационального разбора. У тебя нет своей позиции по теме, ты не участник. Ты судишь по Манифесту (ниже), только по исходному тексту и транскрипту обсуждения.

Твоя задача — определить, что самое рациональное: что из сказанного доказано строго, что вероятно по бритве Оккама, что непроверяемо, где и кто ошибся. Ты не уравниваешь стороны «для баланса»: если один аналитик прав, а другой нет, — скажи это прямо. Если текст в целом рационален — признай это; если это демагогия — назови уловки по имени.

Шкалы. rationality_score — насколько рационален исходный текст: 0 — сплошная демагогия без фактов, 100 — безупречная аргументация с проверяемыми данными. confidence — твоя уверенность в заключении. Оценки аналитиков 1..10: rigor — строгость рассуждения; evidence — работа с фактами и бременем доказывания; charity — благожелательность и стилменнинг; responsiveness — реально ли отвечал коллегам и менял позицию под весом доводов (а не упрямился и не соглашался без причины).

Все текстовые поля пиши на языке «{language}», кратко и конкретно; списки — по 1–5 пунктов, каждый пункт — одна мысль."""


def judge_system_prompt(language: str) -> str:
    return f"{_JUDGE_CORE.format(language=language)}\n\n{MANIFEST}"


def verdict_json_schema() -> dict:
    return Verdict.model_json_schema()


def judge_user(
    text: str,
    question: str | None,
    transcript: str,
    analyst_names: list[str],
    language: str,
    json_schema: str | None = None,
) -> str:
    names = ", ".join(analyst_names)
    prompt = (
        f"{_source_block(text, question)}\n\n"
        f"Аналитики: {names}.\n\n"
        f"Полный транскрипт обсуждения:\n{transcript}\n\n"
        "Вынеси вердикт: сформулируй предмет нейтрально (core_question), дай самое "
        "рациональное заключение (conclusion), оцени рациональность текста и свою уверенность, "
        "разложи установленное / вероятное / неопределённое, оцени ключевые утверждения текста "
        "(claims; если текст не содержит утверждений — пустой список и объяснение в conclusion), "
        "перечисли найденные уловки (fallacies), приведи сильнейшую версию позиции автора "
        "(steelman), критерий опровержения вердикта (falsification) и практическое следствие "
        "(so_what). Оцени КАЖДОГО аналитика ровно один раз, имена бери точно как в транскрипте, "
        f"и назови most_rational. Текстовые поля — на языке «{language}»."
    )
    if json_schema:
        prompt += (
            "\n\nВерни ТОЛЬКО валидный JSON-объект по этой JSON-схеме, без markdown и без "
            f"пояснений до или после:\n{json_schema}"
        )
    return prompt


def verdict_json_schema_text() -> str:
    return json.dumps(verdict_json_schema(), ensure_ascii=False)
